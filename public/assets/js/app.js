function getPsicologoById(id) {
  return dados.psicologos.find(p => p.id === parseInt(id));
}

function getPsicologosDestaque() {
  return dados.psicologos.filter(p => p.destaque);
}

function renderCarousel() {
  const destaques = getPsicologosDestaque();
  const indicators = document.getElementById('carousel-indicators');
  const inner = document.getElementById('carousel-inner');

  if (!indicators || !inner) return;

  destaques.forEach((psi, index) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.setAttribute('data-bs-target', '#carouselDestaques');
    btn.setAttribute('data-bs-slide-to', index);
    btn.setAttribute('aria-label', `Slide ${index + 1}`);
    if (index === 0) {
      btn.classList.add('active');
      btn.setAttribute('aria-current', 'true');
    }
    indicators.appendChild(btn);

    const item = document.createElement('div');
    item.className = `carousel-item${index === 0 ? ' active' : ''}`;
    item.innerHTML = `
      <img src="${psi.imagem_principal}" class="d-block w-100 carousel-img" alt="${psi.nome}">
      <div class="carousel-caption d-block">
        <span class="badge-abordagem">${psi.abordagem}</span>
        <h3 class="carousel-nome">${psi.nome}</h3>
        <p class="carousel-desc d-none d-md-block">${psi.descricao}</p>
        <a href="detalhe.html?id=${psi.id}" class="btn btn-carousel mt-2">Ver Perfil Completo</a>
      </div>
    `;
    inner.appendChild(item);
  });
}

